#!/usr/bin/env python3
"""Build crash-diagnostic symbol tables from roco_ld map files.

The kernel and every user program are linked with -Map. A fatal trap
prints a backtrace of return addresses; these tables let the kernel turn
an address into function+offset without carrying an ELF symbol table.

Two link passes are needed for the kernel: the first produces the map,
this script turns it into assembly, and the second links the table in.
The table only adds .rodata after every kernel section, so no symbol
address changes between the passes.

Usage:
    mksyms.py -o build/ksyms.S --kernel build/ksym-kernel.map \
        --program /bin/shell=build/user-shell.map [--program ...]
"""

import argparse
import sys
from pathlib import Path

TEXT = ".text"


def parse_map(path):
    """Return (text_start, text_end, [(address, name)]) for one map."""
    if not path.exists():
        raise SystemExit(
            f"{path}: missing map file; delete stale build outputs or rebuild")
    text = None
    symbols = []
    mode = None
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line == "sections:":
            mode = "sections"
            continue
        if line == "symbols:":
            mode = "symbols"
            continue
        if not line:
            continue
        parts = line.split()
        if mode == "sections" and len(parts) == 3 and parts[2] == TEXT:
            start = int(parts[0], 16)
            text = (start, start + int(parts[1], 16))
        elif mode == "symbols" and len(parts) == 2:
            symbols.append((int(parts[0], 16), parts[1]))
    if text is None:
        raise SystemExit(f"{path}: no {TEXT} section in map")
    # The linker emits symbols in object order. Keep text symbols that can
    # name a frame: drop assembler-local labels (".L...") and aliases.
    # Linker-provided "__..." markers sort last so "_start" beats
    # "__text_start" for the same address.
    seen = set()
    kept = []
    ordered = sorted(symbols,
                     key=lambda s: (s[0], s[1].startswith("__"), s[1]))
    for address, name in ordered:
        if not text[0] <= address < text[1]:
            continue
        if name.startswith(".") or address in seen:
            continue
        seen.add(address)
        kept.append((address, name))
    return text[0], text[1], kept


class Emitter:
    def __init__(self):
        self.lines = [
            "# Generated by tools/mksyms.py from roco_ld map files. Do not edit.",
            ".section .rodata",
            ".balign 4",
        ]
        self.strings = {}

    def label(self, name):
        self.lines.append(name + ":")

    def word(self, value):
        self.lines.append("    .word 0x%08x" % value)

    def table(self, name, values, fmt="    .word 0x%08x"):
        """Emit a global table of 32-bit words."""
        self.lines.append(".globl " + name)
        self.label(name)
        for value in values:
            self.lines.append(fmt % value)

    def string(self, name):
        """Return the label for a shared string, emitting it later."""
        if name not in self.strings:
            self.strings[name] = ".Lstr%d" % len(self.strings)
        return self.strings[name]

    def render(self):
        lines = list(self.lines)
        lines.append("")
        lines.append("# Shared symbol names.")
        for name, label in self.strings.items():
            lines.append(label + ":")
            lines.append('    .asciz "%s"' % name)
        return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument("--stub", action="store_true",
                        help="emit empty tables (first-pass link placeholder)")
    parser.add_argument("--kernel", type=Path,
                        help="map file for the kernel image")
    parser.add_argument("--program", action="append", default=[],
                        metavar="PATH=MAP",
                        help="user program path and its map file")
    args = parser.parse_args()

    if args.stub:
        # The kernel references the crash tables, so the map-producing link
        # needs placeholder definitions. Only .rodata shifts, never .text,
        # so the real table still matches the addresses in that map.
        tables = [
            ("crash_kernel_text", [0, 0]),
            ("crash_kernel_sym_count", [0]),
            ("crash_kernel_sym_addrs", [0]),
            ("crash_kernel_sym_names", [0]),
            ("crash_program_count", [0]),
            ("crash_program_paths", [0]),
            ("crash_program_text_start", [0]),
            ("crash_program_text_end", [0]),
            ("crash_program_sym_count", [0]),
            ("crash_program_sym_addrs", [0]),
            ("crash_program_sym_names", [0]),
        ]
        lines = [".section .rodata", ".balign 4"]
        for label, values in tables:
            lines.append(".globl " + label)
            lines.append(label + ":")
            lines.extend("    .word 0" for _ in values)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text("\n".join(lines) + "\n")
        return 0

    if args.kernel is None:
        parser.error("--kernel is required unless --stub is given")

    kernel = parse_map(args.kernel)
    programs = []
    for entry in args.program:
        if "=" not in entry:
            parser.error(f"--program expects PATH=MAP, got {entry!r}")
        path, map_path = entry.split("=", 1)
        programs.append((path, parse_map(Path(map_path))))

    out = Emitter()

    # Kernel text bounds and symbols.
    out.table("crash_kernel_text", kernel[0:2])
    out.table("crash_kernel_sym_count", [len(kernel[2])])
    out.table("crash_kernel_sym_addrs", [address for address, _ in kernel[2]])
    out.table("crash_kernel_sym_names",
              [out.string(name) for _, name in kernel[2]], "    .word %s")

    # Per-program symbol tables are referenced by the kernel through a set
    # of parallel arrays, because roco_cc has no structs.
    prefixes = [".Lprog%d" % index for index in range(len(programs))]
    out.table("crash_program_count", [len(programs)])
    out.table("crash_program_paths",
              [p + "_path" for p in prefixes], "    .word %s")
    out.table("crash_program_text_start",
              [program[0] for _, program in programs])
    out.table("crash_program_text_end",
              [program[1] for _, program in programs])
    out.table("crash_program_sym_count",
              [len(program[2]) for _, program in programs], "    .word %d")
    out.table("crash_program_sym_addrs",
              [p + "_addrs" for p in prefixes], "    .word %s")
    out.table("crash_program_sym_names",
              [p + "_names" for p in prefixes], "    .word %s")

    for prefix, (path, (_, _, symbols)) in zip(prefixes, programs):
        out.lines.append("")
        out.lines.append(".balign 4")
        out.label(prefix + "_path")
        out.lines.append('    .asciz "%s"' % path)
        out.lines.append(".balign 4")
        out.label(prefix + "_addrs")
        for address, _ in symbols:
            out.word(address)
        out.lines.append(".balign 4")
        out.label(prefix + "_names")
        for _, name in symbols:
            out.lines.append("    .word " + out.string(name))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(out.render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
