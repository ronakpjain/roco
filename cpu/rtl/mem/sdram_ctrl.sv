// 16-bit SDR SDRAM controller for the IS42S16160J (32 MiB, 4 banks,
// 8192 rows x 512 halfword columns).
//
// Transactions move 32-bit words. Each word is an SDRAM burst of two
// halfwords (BL=2), so a four-word cache line is eight halfword beats.
// Read commands are issued every two cycles; the returned halfword
// pairs are assembled into words, one word per two cycles after CAS
// latency.
//
// One transaction is serviced at a time. The controller keeps a single
// row open per bank and only precharges when the next transaction needs
// a different row or a refresh is due. Transactions must not cross a
// 256-word column boundary (all cache and boot requests are naturally
// aligned), which keeps the command sequencer simple.
//
// The external SDRAM clock is generated by the top level; this module
// is clocked by the same 48 MHz domain.

`default_nettype none

module sdram_ctrl #(
    parameter int CLK_HZ = 48_000_000,
    parameter int CL = 3,
    parameter int T_POWERUP = CLK_HZ / 5000,
    parameter int REFRESH_CYCLES = CLK_HZ / 130_000
) (
  input logic clk,
  input logic rst,
  /* Transaction channel: valid/addr stay stable until ready. */
  input logic req_valid,
  output logic req_ready,
  input logic req_we,
  input logic [22:0] req_word_addr,
  input logic [3:0] req_len,
  /* Write beats: one 32-bit word per beat. */
  input logic wvalid,
  output logic wready,
  input logic [31:0] wdata,
  input logic [3:0] wbe,
  /* Read beats: one 32-bit word per beat. */
  output logic rvalid,
  output logic [31:0] rdata,
  output logic rlast,
  output logic init_done,
  /* SDRAM pins (the clock and CKE are driven by the top level). */
  output logic [12:0] sd_a,
  output logic [1:0] sd_ba,
  output logic sd_cs_n,
  output logic sd_ras_n,
  output logic sd_cas_n,
  output logic sd_we_n,
  output logic [1:0] sd_dqm,
  output logic [15:0] sd_dq_out,
  output logic sd_dq_oe,
  input logic [15:0] sd_dq_in
);

  // Command timing, in cycles at 48 MHz. All values are above the
  // IS42S16160J minimums for the 143 MHz grade.
  localparam int T_RP  = 2;
  localparam int T_RCD = 2;
  localparam int T_RFC = 4;
  localparam int T_MRD = 2;
  localparam int T_WR  = 3;

  // Mode register: CL, burst length 2, sequential.
  localparam logic [12:0] MRS_VALUE = 13'h0001 | (13'(CL) << 4);

  typedef enum logic [4:0] {
    S_POWERUP,
    S_INIT_PRE,
    S_INIT_PRE_WAIT,
    S_INIT_REF,
    S_INIT_REF_WAIT,
    S_INIT_MRS,
    S_INIT_MRS_WAIT,
    S_IDLE,
    S_PRECHARGE,
    S_PRECHARGE_WAIT,
    S_ACT,
    S_ACT_WAIT,
    S_READ,
    S_WRITE,
    S_WR_DRAIN,
    S_REFRESH,
    S_REFRESH_WAIT
  } state_t;

  state_t state;
  logic [15:0] wait_cnt;
  logic [16:0] powerup_cnt;
  logic [8:0] refresh_cnt;
  logic refresh_pending;
  logic pre_for_refresh;
  logic init_refs;

  logic [22:0] cmd_addr;
  logic [3:0] cmd_len;
  logic cmd_we;
  logic [1:0] cmd_bank;
  logic [12:0] cmd_row;
  logic [7:0] cmd_col;

  logic row_open;
  logic [1:0] row_bank;
  logic [12:0] row_addr;

  // Read burst pipeline.
  // Six bits cover CL plus all 32 halfwords of a maximum-length read.
  logic [5:0] rd_t;
  logic [4:0] rd_issue;
  logic [15:0] rd_lo;

  // Write burst pipeline.
  logic [1:0] wr_phase;
  logic [3:0] wr_beat;
  logic [31:0] wr_word;
  logic [3:0] wr_be;

  always_comb begin
    cmd_bank = cmd_addr[22:21];
    cmd_row = cmd_addr[20:8];
    cmd_col = cmd_addr[7:0];
  end

  // --------------------------------------------------------- Command decode
  always_comb begin
    sd_cs_n = 1'b1;
    sd_ras_n = 1'b1;
    sd_cas_n = 1'b1;
    sd_we_n = 1'b1;
    sd_a = 13'd0;
    sd_ba = cmd_bank;
    sd_dqm = 2'b00;
    sd_dq_out = 16'd0;
    sd_dq_oe = 1'b0;
    case (state)
      S_INIT_PRE, S_PRECHARGE: begin
        sd_cs_n = 1'b0;
        sd_ras_n = 1'b0;
        sd_cas_n = 1'b1;
        sd_we_n = 1'b0;
        sd_a[10] = 1'b1;  // precharge all banks
      end
      S_INIT_REF, S_REFRESH: begin
        sd_cs_n = 1'b0;
        sd_ras_n = 1'b0;
        sd_cas_n = 1'b0;
        sd_we_n = 1'b1;
      end
      S_INIT_MRS: begin
        sd_cs_n = 1'b0;
        sd_ras_n = 1'b0;
        sd_cas_n = 1'b0;
        sd_we_n = 1'b0;
        sd_ba = 2'b00;
        sd_a = MRS_VALUE;
      end
      S_ACT: begin
        sd_cs_n = 1'b0;
        sd_ras_n = 1'b0;
        sd_cas_n = 1'b1;
        sd_we_n = 1'b1;
        sd_ba = cmd_bank;
        sd_a = cmd_row;
      end
      S_READ: begin
        if ((rd_t[0] == 1'b0) && (rd_issue <= {1'b0, cmd_len})) begin
          sd_cs_n = 1'b0;
          sd_ras_n = 1'b1;
          sd_cas_n = 1'b0;
          sd_we_n = 1'b1;
          sd_ba = cmd_bank;
          sd_a[8:0] = {cmd_col + {3'b0, rd_issue}, 1'b0};
        end
      end
      S_WRITE: begin
        sd_ba = cmd_bank;
        if (wr_phase == 2'd1) begin
          sd_cs_n = 1'b0;
          sd_ras_n = 1'b1;
          sd_cas_n = 1'b0;
          sd_we_n = 1'b0;
          sd_a[8:0] = {cmd_col + {4'b0, wr_beat}, 1'b0};
          sd_dq_out = wr_word[15:0];
          sd_dq_oe = 1'b1;
          sd_dqm = ~wr_be[1:0];
        end else if (wr_phase == 2'd2) begin
          // Second half of the BL=2 write; no new command.
          sd_dq_out = wr_word[31:16];
          sd_dq_oe = 1'b1;
          sd_dqm = ~wr_be[3:2];
        end
      end
      default: begin
      end
    endcase
  end

  assign req_ready = (state == S_IDLE) && init_done && !refresh_pending;
  assign wready = (state == S_WRITE) && (wr_phase == 2'd0);

  // ------------------------------------------------------------- Sequencer
  always_ff @(posedge clk) begin
    if (rst) begin
      state <= S_POWERUP;
      wait_cnt <= '0;
      powerup_cnt <= '0;
      refresh_cnt <= '0;
      refresh_pending <= 1'b0;
      pre_for_refresh <= 1'b0;
      init_refs <= 1'b0;
      init_done <= 1'b0;
      cmd_addr <= '0;
      cmd_len <= '0;
      cmd_we <= 1'b0;
      row_open <= 1'b0;
      row_bank <= '0;
      row_addr <= '0;
      rd_t <= '0;
      rd_issue <= '0;
      rd_lo <= '0;
      rvalid <= 1'b0;
      rdata <= '0;
      wr_phase <= '0;
      wr_beat <= '0;
      wr_word <= '0;
      wr_be <= '0;
    end else begin
      rvalid <= 1'b0;
      rlast <= 1'b0;

      // Refresh interval counter.
      if (refresh_cnt >= 9'(REFRESH_CYCLES)) begin
        refresh_pending <= 1'b1;
      end else begin
        refresh_cnt <= refresh_cnt + 9'd1;
      end

      case (state)
        S_POWERUP: begin
          powerup_cnt <= powerup_cnt + 17'd1;
          if (powerup_cnt >= 17'(T_POWERUP)) begin
            state <= S_INIT_PRE;
          end
        end

        S_INIT_PRE: begin
          state <= S_INIT_PRE_WAIT;
          wait_cnt <= 16'(T_RP - 1);
        end

        S_INIT_PRE_WAIT: begin
          if (wait_cnt == 16'd0) begin
            state <= S_INIT_REF;
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_INIT_REF: begin
          state <= S_INIT_REF_WAIT;
          wait_cnt <= 16'(T_RFC - 1);
        end

        S_INIT_REF_WAIT: begin
          if (wait_cnt == 16'd0) begin
            if (init_refs) begin
              state <= S_INIT_MRS;
            end else begin
              init_refs <= 1'b1;
              state <= S_INIT_REF;
            end
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_INIT_MRS: begin
          state <= S_INIT_MRS_WAIT;
          wait_cnt <= 16'(T_MRD - 1);
        end

        S_INIT_MRS_WAIT: begin
          if (wait_cnt == 16'd0) begin
            init_done <= 1'b1;
            refresh_cnt <= 9'd0;
            state <= S_IDLE;
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_IDLE: begin
          if (refresh_pending) begin
            refresh_pending <= 1'b0;
            refresh_cnt <= 9'd0;
            pre_for_refresh <= 1'b1;
            if (row_open) begin
              state <= S_PRECHARGE;
            end else begin
              state <= S_REFRESH;
            end
          end else if (req_valid) begin
            cmd_addr <= req_word_addr;
            cmd_len <= req_len;
            cmd_we <= req_we;
            pre_for_refresh <= 1'b0;
            if (row_open && (row_bank == req_word_addr[22:21]) &&
                (row_addr == req_word_addr[20:8])) begin
              if (req_we) begin
                state <= S_WRITE;
                wr_phase <= 2'd0;
                wr_beat <= 4'd0;
              end else begin
                state <= S_READ;
                rd_t <= 6'd0;
                rd_issue <= 5'd0;
              end
            end else if (row_open) begin
              state <= S_PRECHARGE;
            end else begin
              state <= S_ACT;
            end
          end
        end

        S_PRECHARGE: begin
          state <= S_PRECHARGE_WAIT;
          wait_cnt <= 16'(T_RP - 1);
          row_open <= 1'b0;
        end

        S_PRECHARGE_WAIT: begin
          if (wait_cnt == 16'd0) begin
            if (pre_for_refresh) begin
              state <= S_REFRESH;
            end else begin
              state <= S_ACT;
            end
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_ACT: begin
          state <= S_ACT_WAIT;
          wait_cnt <= 16'(T_RCD - 1);
          row_open <= 1'b1;
          row_bank <= cmd_bank;
          row_addr <= cmd_row;
        end

        S_ACT_WAIT: begin
          if (wait_cnt == 16'd0) begin
            if (cmd_we) begin
              state <= S_WRITE;
              wr_phase <= 2'd0;
              wr_beat <= 4'd0;
            end else begin
              state <= S_READ;
              rd_t <= 6'd0;
              rd_issue <= 5'd0;
            end
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_READ: begin
          rd_t <= rd_t + 6'd1;
          if ((rd_t[0] == 1'b0) && (rd_issue <= {1'b0, cmd_len})) begin
            rd_issue <= rd_issue + 5'd1;
          end
          if (rd_t >= 6'(CL) + 6'd1) begin
            if (((rd_t - 6'(CL) - 6'd1) & 6'd1) == 6'd0) begin
              rd_lo <= sd_dq_in;
            end else begin
              rdata <= {sd_dq_in, rd_lo};
              rvalid <= 1'b1;
              rlast <= ((rd_t - 6'(CL) - 6'd1) >> 1) == {2'b0, cmd_len};
              if (((rd_t - 6'(CL) - 6'd1) >> 1) == {2'b0, cmd_len}) begin
                rd_t <= 6'd0;
                rd_issue <= 5'd0;
                state <= S_IDLE;
              end
            end
          end
        end

        S_WRITE: begin
          if (wr_phase == 2'd0) begin
            if (wvalid) begin
              wr_word <= wdata;
              wr_be <= wbe;
              wr_phase <= 2'd1;
            end
          end else if (wr_phase == 2'd1) begin
            wr_phase <= 2'd2;
          end else begin
            wr_phase <= 2'd0;
            if (wr_beat == cmd_len) begin
              state <= S_WR_DRAIN;
              wait_cnt <= 16'(T_WR - 1);
            end else begin
              wr_beat <= wr_beat + 4'd1;
            end
          end
        end

        S_WR_DRAIN: begin
          if (wait_cnt == 16'd0) begin
            state <= S_IDLE;
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        S_REFRESH: begin
          state <= S_REFRESH_WAIT;
          wait_cnt <= 16'(T_RFC - 1);
          pre_for_refresh <= 1'b0;
          row_open <= 1'b0;
        end

        S_REFRESH_WAIT: begin
          if (wait_cnt == 16'd0) begin
            state <= S_IDLE;
          end else begin
            wait_cnt <= wait_cnt - 16'd1;
          end
        end

        default: begin
          state <= S_IDLE;
        end
      endcase
    end
  end

endmodule
